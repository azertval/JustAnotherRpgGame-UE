def district_for(u, v):
    for key, (_, poly, _, _) in REGIONS.items():
        if inside(u, v, poly):
            return key
    return None


def inside(x, y, polygon):
    result = False
    for a,b in zip(polygon, polygon[1:]+polygon[:1]):
        if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:
            result = not result
    return result
